def build(ep):
    shots, end = SH[ep]
    sp = SPEC[ep]
    sp['shots'] = [(s[0], fmt(s[1]), 'done' if s[5] else ('res' if s[2] == 'res' else 'real'), s[3], s[4]) for s in shots]
    sp['shots_lead'] = f'粗剪样片约 {fmt(end)}。已渲染的动画、资料卡、问题卡和片头片尾都已就位；其余镜头是占位画面。旁白里括号中的内容，要按实测结果改写。'
    html = kit.page(sp)
    p = f'/tmp/claude-0/-home-claude/2bae78cb-602b-5cf3-a87b-834191483ac2/scratchpad/{ep.lower()}-plan.html'
    open(p, 'w', encoding='utf-8').write(html)
    rc = [(s[0], s[1], '待结果' if s[2] == 'res' else '实拍', s[3], s[4], s[5]) for s in shots]
    kit.roughcut(ep.lower(), TAG[ep], rc, end, f'{ep}_粗剪样片')
    print('built', ep, p)

if __name__ == '__main__':
    what = sys.argv[1] if len(sys.argv) > 1 else 'all'
    if what in ('cards', 'all'):
        kit.render_all(CARDS)
    if what in ('build', 'all'):
        for ep in SH: build(ep)
