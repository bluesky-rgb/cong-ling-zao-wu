    html = kit.page(sp)
    p = f'/tmp/claude-0/-home-claude/2bae78cb-602b-5cf3-a87b-834191483ac2/scratchpad/{ep.lower()}-plan.html'
    open(p, 'w', encoding='utf-8').write(html)
    rc = [(s[0], s[1], '待结果' if s[2] == 'res' else '实拍', s[3], s[4], s[5]) for s in shots]
